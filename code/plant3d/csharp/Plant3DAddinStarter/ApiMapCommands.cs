// ApiMapCommands.cs
//   P3DAPIMAP : writes a map of the Plant 3D .NET API as it exists on THIS PC - assemblies, namespaces, public
//               types with their base type, and the inheritance tree of the DWG object classes - to a
//               Markdown file. Optionally lists the public members of one type on the command line.
// The Plant 3D API help is thin. This command uses .NET reflection on the loaded Plant 3D assemblies, so what
// it prints is the truth for your release. No Plant 3D type is referenced here: it only reads metadata.
using System.Reflection;
using System.Text;
using Autodesk.AutoCAD.ApplicationServices;
using Autodesk.AutoCAD.DatabaseServices;
using Autodesk.AutoCAD.EditorInput;
using Autodesk.AutoCAD.Runtime;
using AcApp = Autodesk.AutoCAD.ApplicationServices.Application;

[assembly: CommandClass(typeof(Plant3DAddinStarter.ApiMapCommands))]

namespace Plant3DAddinStarter
{
    public class ApiMapCommands
    {
        [CommandMethod("P3DAPIMAP")]
        public void ApiMap()
        {
            Document? doc = AcApp.DocumentManager.MdiActiveDocument;
            if (doc == null) return;
            Editor ed = doc.Editor;
            Report.Run("P3DAPIMAP", () =>
            {
                List<Assembly> assemblies = PlantAssemblies();
                if (assemblies.Count == 0)
                    throw new InvalidOperationException("No Plant 3D assembly is loaded. Run this in Plant 3D with a project open.");

                string header = $"Generated by P3DAPIMAP on {DateTime.Now:yyyy-MM-dd HH:mm} - AutoCAD {AcApp.GetSystemVariable("ACADVER")}, " +
                                $"`{HostApplicationServices.Current.UserRegistryProductRootKey}`.";
                string map = BuildMap(assemblies, header, out List<Type> all);
                string path = Report.OutputFile("Plant3D", "apimap", "md");
                Report.WriteText(path, map);
                ed.WriteMessage($"\n{assemblies.Count} Plant 3D assemblies, {all.Count} public types -> {path}");

                // optional: the members of one type, e.g. DataLinksManager
                PromptResult r = ed.GetString("\nType name to list members of, e.g. DataLinksManager <none>: ");
                if (r.Status != PromptStatus.OK || string.IsNullOrWhiteSpace(r.StringResult)) return;
                string wanted = r.StringResult.Trim();
                List<Type> hits = all.Where(t => string.Equals(t.Name, wanted, StringComparison.OrdinalIgnoreCase) ||
                                                 string.Equals(t.FullName, wanted, StringComparison.OrdinalIgnoreCase)).ToList();
                if (hits.Count == 0) ed.WriteMessage($"\nNo public type named '{wanted}' in the loaded Plant 3D assemblies.");
                foreach (Type t in hits)
                {
                    ed.WriteMessage($"\n{Describe(t)}   [{t.Assembly.GetName().Name}]");
                    foreach (string line in Members(t)) ed.WriteMessage($"\n    {line}");
                }
            });
            ed.WriteMessage("\n");
        }

        /// <summary>The Plant 3D assemblies that are loaded right now: their names start with PnP or PnID.</summary>
        internal static List<Assembly> PlantAssemblies()
        {
            return AppDomain.CurrentDomain.GetAssemblies()
                .Where(a => !a.IsDynamic && IsPlantName(a.GetName().Name))
                .OrderBy(a => a.GetName().Name, StringComparer.OrdinalIgnoreCase)
                .ToList();
        }

        /// <summary>True for the simple name of a Plant 3D assembly, e.g. "PnPDataLinks" (not its .resources).</summary>
        internal static bool IsPlantName(string? name) =>
            name != null &&
            (name.StartsWith("PnP", StringComparison.OrdinalIgnoreCase) || name.StartsWith("PnID", StringComparison.OrdinalIgnoreCase)) &&
            !name.EndsWith(".resources", StringComparison.OrdinalIgnoreCase);

        /// <summary>Public types of an assembly; survives types whose dependencies cannot be loaded.</summary>
        private static List<Type> PublicTypes(Assembly asm)
        {
            Type?[] types;
            try { types = asm.GetTypes(); }
            catch (ReflectionTypeLoadException ex) { types = ex.Types; }
            return types.Where(t => t != null && (t.IsPublic || t.IsNestedPublic)).Select(t => t!)
                        .OrderBy(t => t.FullName, StringComparer.Ordinal).ToList();
        }

        /// <summary>The whole map as Markdown text. <paramref name="all"/> returns every public type found.</summary>
        internal static string BuildMap(List<Assembly> assemblies, string header, out List<Type> all)
        {
            all = new List<Type>();
            var sb = new StringBuilder();
            sb.AppendLine("# Plant 3D .NET API map");
            sb.AppendLine();
            sb.AppendLine(header);
            sb.AppendLine("Only assemblies that are loaded at this moment are listed (open a P&ID and a 3D model first to see more).");

            // ---- part 1: assembly -> namespace -> type : base type
            foreach (Assembly asm in assemblies)
            {
                AssemblyName name = asm.GetName();
                List<Type> types = PublicTypes(asm);
                all.AddRange(types);
                sb.AppendLine();
                sb.AppendLine($"## {name.Name} {name.Version}");
                sb.AppendLine();
                sb.AppendLine($"`{asm.Location}` - {types.Count} public types");
                foreach (IGrouping<string, Type> ns in types.GroupBy(t => t.Namespace ?? "(no namespace)").OrderBy(g => g.Key, StringComparer.Ordinal))
                {
                    sb.AppendLine();
                    sb.AppendLine($"### {ns.Key}");
                    sb.AppendLine();
                    foreach (Type t in ns) sb.AppendLine("- " + Describe(t));
                }
            }

            // ---- part 2: the classes that live in a DWG (derived from AutoCAD's DBObject), as a tree
            sb.AppendLine();
            sb.AppendLine("## Inheritance tree of the DWG object classes");
            sb.AppendLine();
            sb.AppendLine("Classes in *italics* are AutoCAD base classes; everything else is Plant 3D.");
            sb.AppendLine();
            AppendTree(sb, all.Where(t => t.IsClass && typeof(DBObject).IsAssignableFrom(t)).ToList());
            return sb.ToString();
        }

        // ---------------------------------------------------------------- formatting

        internal static string Describe(Type t)
        {
            bool isDelegate = typeof(Delegate).IsAssignableFrom(t);
            string kind = t.IsEnum ? "enum" : t.IsInterface ? "interface" : t.IsValueType ? "struct" : isDelegate ? "delegate"
                        : t.IsAbstract && t.IsSealed ? "static class" : t.IsAbstract ? "abstract class" : "class";
            string text = $"{kind} `{Short(t)}`";
            Type? b = t.BaseType;
            if (t.IsClass && !isDelegate && b != null && b != typeof(object)) text += $" : `{Short(b)}`";
            return text;
        }

        /// <summary>Readable type name: Part, List&lt;string&gt;, int[]; nested types as Outer.Inner.</summary>
        internal static string Short(Type t)
        {
            if (t.IsByRef) return "ref " + Short(t.GetElementType()!);
            if (t.IsArray) return Short(t.GetElementType()!) + "[]";
            if (t.IsPointer) return Short(t.GetElementType()!) + "*";
            if (t.IsGenericParameter) return t.Name;
            if (t == typeof(void)) return "void";
            if (t == typeof(string)) return "string";
            if (t == typeof(int)) return "int";
            if (t == typeof(bool)) return "bool";
            if (t == typeof(double)) return "double";
            if (t == typeof(object)) return "object";
            string name = t.Name;
            if (t.IsGenericType)
            {
                int tick = name.IndexOf('`');
                if (tick > 0) name = name.Substring(0, tick);
                name += "<" + string.Join(", ", t.GetGenericArguments().Select(Short)) + ">";
            }
            return t.IsNested && t.DeclaringType != null ? Short(t.DeclaringType) + "." + name : name;
        }

        private static void AppendTree(StringBuilder sb, List<Type> plantTypes)
        {
            // parent -> children. Base classes outside the Plant assemblies (Entity, Curve, BlockReference...)
            // are added on the way up, until AutoCAD's DBObject, which becomes the root.
            var children = new Dictionary<Type, List<Type>>();
            var roots = new List<Type>();
            var known = new HashSet<Type>(plantTypes);
            foreach (Type t in plantTypes)
            {
                Type child = t;
                while (true)
                {
                    Type? parent = child.BaseType;
                    if (parent == null || !typeof(DBObject).IsAssignableFrom(parent))
                    {
                        if (!roots.Contains(child)) roots.Add(child);
                        break;
                    }
                    if (!children.TryGetValue(parent, out List<Type>? list)) children[parent] = list = new List<Type>();
                    if (!list.Contains(child)) list.Add(child);
                    if (known.Contains(parent)) break;          // 'parent' adds the rest of the chain itself
                    child = parent;
                }
            }
            foreach (Type root in roots.OrderBy(t => t.Name, StringComparer.Ordinal)) Append(root, 0);

            void Append(Type t, int depth)
            {
                string label = known.Contains(t) ? $"`{Short(t)}`" + (t.IsAbstract ? " (abstract)" : "") : $"*{Short(t)}*";
                sb.AppendLine(new string(' ', depth * 2) + "- " + label);
                if (!children.TryGetValue(t, out List<Type>? list)) return;
                foreach (Type c in list.OrderBy(x => x.Name, StringComparer.Ordinal)) Append(c, depth + 1);
            }
        }

        /// <summary>Public members declared by the type itself, one line each.</summary>
        internal static List<string> Members(Type t)
        {
            const BindingFlags flags = BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;
            var lines = new List<string>();
            if (t.IsEnum) { lines.AddRange(Enum.GetNames(t)); return lines; }
            try
            {
                foreach (ConstructorInfo c in t.GetConstructors(flags))
                    lines.Add($"new {Short(t)}({Parameters(c)})");
                foreach (PropertyInfo p in t.GetProperties(flags).OrderBy(p => p.Name, StringComparer.Ordinal))
                {
                    ParameterInfo[] index = p.GetIndexParameters();
                    string indexer = index.Length == 0 ? "" : "[" + string.Join(", ", index.Select(a => $"{Short(a.ParameterType)} {a.Name}")) + "]";
                    string access = (p.CanRead ? "get; " : "") + (p.CanWrite ? "set; " : "");
                    lines.Add($"{Static(p.GetAccessors().FirstOrDefault())}{Short(p.PropertyType)} {p.Name}{indexer} {{ {access}}}");
                }
                foreach (EventInfo e in t.GetEvents(flags).OrderBy(e => e.Name, StringComparer.Ordinal))
                    lines.Add($"event {(e.EventHandlerType == null ? "?" : Short(e.EventHandlerType))} {e.Name}");
                foreach (MethodInfo m in t.GetMethods(flags).Where(m => !m.IsSpecialName).OrderBy(m => m.Name, StringComparer.Ordinal))
                    lines.Add($"{Static(m)}{Short(m.ReturnType)} {m.Name}({Parameters(m)})");
            }
            catch (System.Exception ex)             // a member whose types cannot be loaded
            {
                lines.Add($"(stopped: {ex.GetType().Name}: {ex.Message})");
            }
            return lines;
        }

        private static string Static(MethodBase? m) => m != null && m.IsStatic ? "static " : "";

        private static string Parameters(MethodBase m) =>
            string.Join(", ", m.GetParameters().Select(p => $"{Short(p.ParameterType)} {p.Name}"));
    }
}
